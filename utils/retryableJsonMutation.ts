/** Preserve one logical write across rapid taps, network timeouts and page reloads. */
export function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(v=>canonicalJson(v) ?? 'null').join(',')}]`;
  if (value && typeof value==='object') return `{${Object.entries(value).filter(([,v])=>v!==undefined).sort(([a],[b])=>a<b?-1:a>b?1:0).map(([k,v])=>`${JSON.stringify(k)}:${canonicalJson(v)}`).join(',')}}`;
  return JSON.stringify(value) ?? 'null';
}
interface PendingMutation {key:string;url:string;method:string;body:string;signature:string;createdAt:number;}
export function createRetryableJsonMutation(storageKey?: string, request: typeof fetch = (...args)=>fetch(...args), timeoutMs=20000) {
  let pending:PendingMutation|null=null;
  let inFlight:Promise<Response>|null=null;
  const storage=()=>typeof window==='undefined' ? null : window.sessionStorage;
  try {const saved=storageKey&&storage()?.getItem(storageKey);if(saved){const value=JSON.parse(saved);if(typeof value.key==='string'&&typeof value.body==='string'&&value.createdAt>Date.now()-86400000)pending=value;}}catch{}
  function persist(){try{if(storageKey){if(pending)storage()?.setItem(storageKey,JSON.stringify(pending));else storage()?.removeItem(storageKey);}}catch{}}
  async function perform(snapshot:PendingMutation) {
    for(let attempt=0;attempt<2;attempt++) {
      const abort=new AbortController();const timer=setTimeout(()=>abort.abort(),timeoutMs);
      try {
        const response=await request(snapshot.url,{method:snapshot.method,headers:{'Content-Type':'application/json','Idempotency-Key':snapshot.key},body:snapshot.body,signal:abort.signal,credentials:'include'});
        if([502,503,504].includes(response.status)&&attempt===0)continue;
        if(response.ok || [400,403,404,409,422].includes(response.status)){pending=null;persist();}
        return response;
      }catch(error){if(attempt===1)throw error;}finally{clearTimeout(timer);}
    }
    throw new Error('저장 결과를 확인하지 못했습니다. 같은 요청으로 다시 확인해 주세요.');
  }
  function run(snapshot:PendingMutation){
    if(inFlight)return inFlight.then(r=>r.clone());
    inFlight=perform(snapshot).finally(()=>{inFlight=null;});
    return inFlight.then(r=>r.clone());
  }
  return {
    get hasPending(){return Boolean(pending);},
    send(url:string,body:unknown,options?:{method?:string;intent?:unknown}){
      const method=options?.method || 'POST';
      const intent=JSON.parse(JSON.stringify(options?.intent ?? body,(key,value)=>key==='capturedAt'?undefined:value));
      const signature=`${method}:${url}:${canonicalJson(intent)}`;
      if(pending && pending.signature!==signature)throw new Error('이전 저장 결과를 먼저 확인한 후 내용을 변경해 주세요.');
      if(!pending || pending.signature!==signature)pending={key:crypto.randomUUID(),url,method,body:JSON.stringify(body),signature,createdAt:Date.now()};
      persist();return run(pending);
    },
    retry(){if(!pending)return Promise.reject(new Error('확인할 저장 요청이 없습니다.'));return run(pending);},
  };
}
/** These IDs are generated by QuickDispatch for an otherwise unchanged creation form. */
export function quickDispatchIntent(items:Record<string,unknown>[]) {
  return items.map(item=>Object.fromEntries(Object.entries(item).filter(([key])=>!['bookingNo','eventId','groupId'].includes(key))));
}
